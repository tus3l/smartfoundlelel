-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'users', 'categories', 'neighborhoods', 'lost_items', 'found_items', 'matches',
        'claim_requests', 'conversations', 'chat_messages', 'feedbacks'
    ]
    loop
        execute format('drop trigger if exists trg_%1$s_updated_at on public.%1$I', table_name);
        execute format(
            'create trigger trg_%1$s_updated_at before update on public.%1$I
             for each row execute function public.set_updated_at()',
            table_name
        );
    end loop;
end;
$$;


-- ---------------------------------------------------------------------
-- Row Level Security: on for every table, no policies (server-only access).
-- ---------------------------------------------------------------------
do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'users', 'categories', 'neighborhoods', 'lost_items', 'found_items', 'matches',
        'claim_requests', 'conversations', 'chat_messages', 'item_images', 'notifications',
        'otp_verifications', 'feedbacks', 'system_logs'
    ]
    loop
        execute format('alter table public.%I enable row level security', table_name);
    end loop;
end;
$$;


