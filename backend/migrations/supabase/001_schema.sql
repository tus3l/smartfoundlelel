-- Keeps updated_at current (replaces MySQL "ON UPDATE CURRENT_TIMESTAMP").
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;


