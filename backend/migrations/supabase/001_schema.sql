create or replace view public.vw_category_statistics
with (security_invoker = true) as
select
    c.id as category_id,
    c.name_ar,
    c.name_en,
    (select count(*) from public.lost_items l where l.category_id = c.id) as lost_count,
    (select count(*) from public.found_items f where f.category_id = c.id) as found_count
from public.categories c;

create or replace view public.vw_smart_matches
with (security_invoker = true) as
select
    m.id as match_id,
    m.overall_score,
    m.category_score,
    m.description_score,
    m.location_score,
    m.date_score,
    m.color_score,
    m.brand_score,
    m.image_score,
    m.status as match_status,
    l.id as lost_item_id,
    l.title as lost_item_title,
    l.color as lost_item_color,
    l.brand as lost_item_brand,
    l.lost_date,
    f.id as found_item_id,
    f.title as found_item_title,
    f.color as found_item_color,
    f.brand as found_item_brand,
    f.found_date,
    c.name_ar as category_name,
    m.created_at as matched_at
from public.matches m
join public.lost_items l on l.id = m.lost_item_id
join public.found_items f on f.id = m.found_item_id
join public.categories c on c.id = l.category_id;

create or replace view public.vw_system_statistics
with (security_invoker = true) as
select
    (select count(*) from public.users where status = 'active') as active_users,
    (select count(*) from public.lost_items) as total_lost_items,
    (select count(*) from public.lost_items where status = 'open') as active_lost_items,
    (select count(*) from public.found_items) as total_found_items,
    (select count(*) from public.found_items where status = 'available') as available_found_items,
    (select count(*) from public.matches) as total_matches,
    (select count(*) from public.matches where overall_score >= 80) as high_confidence_matches,
    (select count(*) from public.claim_requests) as total_claim_requests,
    (select count(*) from public.claim_requests where status = 'pending') as pending_claims,
    (select count(*) from public.claim_requests where status = 'completed') as completed_claims,
    (select count(*) from public.found_items where status = 'returned') as returned_items,
    (select count(*) from public.feedbacks where status in ('open', 'in_progress')) as open_support_requests;


-- ---------------------------------------------------------------------
-- Supabase API roles: no direct access to views or the trigger function.
-- (Skipped automatically on plain Postgres where these roles don't exist.)
-- ---------------------------------------------------------------------
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated') then
        revoke all on public.vw_category_statistics, public.vw_smart_matches, public.vw_system_statistics
            from anon, authenticated;
        revoke execute on function public.set_updated_at() from public, anon, authenticated;
    end if;
end;
$$;
